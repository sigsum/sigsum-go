func TestSignMLDSA44(t *testing.T) {
	pub, signer, err := NewMLDSA44KeyPair()
	if err != nil {
		t.Fatal(err)
	}
	msg := []byte("foo")
	sig, err := signer.Sign(msg)
	if err != nil {
		t.Fatal(err)
	}
	if !pub.Verify(msg, &sig) {
		t.Errorf("MLDSA44 signature verification failed")
	}
	if pub.Verify(msg[:1], &sig) {
		t.Errorf("MLDSA44 signature on wrong message not rejected")
	}
	sig[17] ^= 1
	if pub.Verify(msg, &sig) {
		t.Errorf("bad MLDSA44 signature not rejected")
	}
}

func TestPrivateMLDSA44(t *testing.T) {
	pub, signer, err := NewMLDSA44KeyPair()
	if err != nil {
		t.Fatal(err)
	}
	priv := signer.Private()
	signer2 := NewMLDSA44Signer(&priv)
	if got := signer2.Public(); got != pub {
		t.Errorf("roundtrip via .Private() and NewMLDSA44Signer failed. got: %x, want: %x",
			got, pub)
	}
}

